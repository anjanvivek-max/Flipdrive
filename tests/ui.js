// End-to-end UI/controls test against the real page. Prints PASS/FAIL lines.
const { chromium } = require('playwright');
const OUT = process.argv[2];
let fails = 0;
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1280, height: 720 } });
  const p = await ctx.newPage();
  const errs = [];
  p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
  p.on('pageerror', (e) => errs.push('PAGEERROR: ' + e.message));
  await p.goto('http://127.0.0.1:8137/index.html');
  await p.waitForTimeout(800);
  const q = (fn, arg) => p.evaluate(fn, arg);
  const scr = () => q(() => FD.App.screen);
  const st = () => q(() => FD.App.stateName());

  ok((await scr()) === 'title' && (await st()) === 'title', 'boots to title screen, state "title"');
  // --- tutorial on first play
  await p.click('#btnPlay');
  ok((await scr()) === 'tutorial', 'first PLAY opens tutorial');
  const t0 = await q(() => FD.App.run.world.time + FD.App.run.count);
  await p.waitForTimeout(500);
  const t1 = await q(() => FD.App.run.world.time + FD.App.run.count);
  ok(Math.abs(t0 - t1) < 1e-6, 'simulation frozen while tutorial is open');
  for (let i = 0; i < 4; i++) await p.click('#tutNext');
  ok((await scr()) === 'none', 'tutorial finishes and gameplay starts');
  ok((await q(() => FD.App.save.tutorialSeen)) === true, 'tutorialSeen saved');
  ok((await st()) === 'count', 'state = count (3s countdown)');
  await p.waitForTimeout(3400);
  ok((await st()) === 'drive', 'countdown ends -> drive');
  // --- keyboard throttle
  await p.keyboard.down('ArrowUp');
  await p.waitForTimeout(2000);
  const mph = await q(() => FD.Units.toMph(FD.App.run.vehicle.speed));
  ok(mph > 30, 'ArrowUp accelerates (mph=' + mph.toFixed(0) + ')');
  await p.keyboard.down('Space');
  await p.waitForTimeout(600);
  ok(await q(() => FD.App.run.vehicle.boosting), 'Space boosts');
  await p.keyboard.up('Space'); await p.keyboard.up('ArrowUp');
  await p.keyboard.down('KeyS'); await p.waitForTimeout(1500); await p.keyboard.up('KeyS');
  ok(true, 'brake key handled without error');
  // --- pause
  await p.keyboard.press('Escape');
  ok((await scr()) === 'pause', 'Escape opens pause');
  const w0 = await q(() => FD.App.run.world.time);
  await p.waitForTimeout(500);
  ok(Math.abs(w0 - (await q(() => FD.App.run.world.time))) < 1e-9, 'physics frozen while paused');
  await p.keyboard.press('Escape');
  ok((await scr()) === 'none', 'Escape resumes');
  await p.click('#btnPause');
  ok((await scr()) === 'pause', 'HUD pause button works');
  await p.click('#pSettings');
  ok((await scr()) === 'settings', 'pause -> settings');
  await p.fill('#setMaster', '40');
  await p.evaluate(() => document.getElementById('setMaster').dispatchEvent(new Event('input', { bubbles: true })));
  ok(Math.abs((await q(() => FD.Audio.vol.master)) - 0.4) < 0.01, 'master volume slider applies');
  await p.check('#setMute');
  ok(await q(() => FD.Audio.muted), 'mute checkbox applies');
  await p.uncheck('#setMute');
  await p.keyboard.press('Escape');
  ok((await scr()) === 'pause', 'Escape in settings goes back to pause');
  await p.click('#pResume');
  ok((await scr()) === 'none', 'resume button works');
  // --- restart (R)
  const runBefore = await q(() => { window._r = FD.App.run; return 1; });
  await p.keyboard.press('KeyR');
  ok((await q(() => FD.App.run !== window._r)) && (await st()) === 'count', 'R restarts level (new run, state count)');
  await p.waitForTimeout(3300);
  // --- crash + retry
  await q(() => FD.App.run.crash('TEST CRASH'));
  ok((await st()) === 'crashed', 'state = crashed');
  await p.waitForFunction(() => FD.App.screen === 'crash', null, { timeout: 8000 }).catch(() => {});
  ok((await scr()) === 'crash', 'crash screen shown');
  await p.keyboard.press('Enter');
  await p.waitForTimeout(100);
  ok((await st()) === 'count' && (await scr()) === 'none', 'Enter on crash screen retries');
  await p.waitForTimeout(3300);
  // --- results via bot + saves
  await q(() => { const A = FD.App; A.restartLevel(); A.run.count = 0.05; const L = A.run.level; A.debugBot = FD.makeBot({ boost: [L.info.rampStart - 150, L.info.rampStart + 300], flip: 1 }); });
  const t = Date.now();
  while ((await scr()) !== 'results' && Date.now() - t < 60000) await sleep(300);
  ok((await scr()) === 'results', 'finish -> results screen (' + ((Date.now() - t) / 1000).toFixed(0) + 's)');
  await p.screenshot({ path: OUT + '/ui_results.png' });
  const best = await q(() => JSON.parse(localStorage.getItem('flipdrive.save')).best);
  ok(best.coastal && best.coastal.pickup && best.coastal.pickup.score > 5000, 'best score saved: ' + JSON.stringify(best.coastal && best.coastal.pickup));
  const rec = await q(() => JSON.parse(localStorage.getItem('flipdrive.save')).records);
  ok(rec.topMph > 50 && rec.runs === 1, 'records saved: ' + JSON.stringify(rec));
  await p.click('#rNext');
  ok((await q(() => FD.App.levelIdx)) === 1 && (await st()) === 'count', 'NEXT LEVEL starts level 2');
  await q(() => { FD.App.debugBot = null; });
  // --- menus
  await p.keyboard.press('Escape'); await p.click('#pGarage');
  ok((await scr()) === 'garage' && (await q(() => FD.App.mode)) === 'attract', 'pause -> garage (back to attract)');
  await p.waitForTimeout(300);
  await p.screenshot({ path: OUT + '/ui_garage.png' });
  await p.click('#garageCards .card[data-id="suv"] [data-select]');
  ok((await q(() => FD.App.vehicleId)) === 'suv', 'garage selects SUV');
  await p.click('#garageCards .card[data-id="suv"] [data-susp] button[data-i="2"]');
  ok((await q(() => FD.App.save.susp)) === 2, 'SUV suspension HIGH selectable');
  await p.click('[data-screen="garage"] [data-back]');
  ok((await scr()) === 'title', 'garage back -> title');
  await p.click('#btnLevels');
  await p.waitForTimeout(200);
  await p.screenshot({ path: OUT + '/ui_levels.png' });
  await p.click('#levelCards .card[data-i="3"] [data-play]');
  ok((await q(() => FD.App.levelIdx)) === 3 && (await q(() => FD.App.run.vehicle.spec.id)) === 'suv', 'level select PLAY starts flood level with SUV');
  ok((await q(() => FD.App.run.vehicle.suspName)) === 'HIGH', 'SUV uses saved HIGH suspension');
  await p.waitForTimeout(3400);
  await p.keyboard.press('KeyC');
  ok((await q(() => FD.App.run.vehicle.suspName)) !== 'HIGH', 'C cycles suspension in-game');
  await p.keyboard.press('KeyM');
  ok(await q(() => FD.Audio.muted), 'M toggles mute');
  await p.keyboard.press('KeyM');
  await p.keyboard.press('Escape'); await p.click('#pQuit');
  ok((await scr()) === 'title', 'pause -> main menu');
  await p.click('#btnHow'); ok((await scr()) === 'tutorial', 'HOW TO PLAY opens tutorial from title');
  await p.click('#tutSkip'); ok((await scr()) === 'title', 'skip returns to title');
  // --- reload persistence
  await p.reload(); await p.waitForTimeout(600);
  ok((await q(() => FD.App.vehicleId)) === 'suv' && (await q(() => FD.App.levelIdx)) === 3, 'selection persists across reload');
  console.log('console/page errors:', errs.length ? errs.join(' | ') : 'none');
  if (errs.length) fails++;
  console.log(fails ? ('FAILED: ' + fails) : 'ALL PASSED');
  await b.close();
  process.exit(fails ? 1 : 0);
})();
